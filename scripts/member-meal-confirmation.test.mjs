import assert from 'node:assert/strict';
import { installTestNutritionCatalog } from './setup-test-nutrition-catalog.mjs';
import { generateDailyMealPlan } from '../src/utils/mealPlanEngine.ts';
import { calculateMacros } from '../src/utils/nutritionHelpers.ts';
import { isCurrentMealConfirmation } from '../src/utils/memberMealConfirmation.ts';
installTestNutritionCatalog();
const plan=generateDailyMealPlan(calculateMacros(2100,85,'weight_loss',178),85,{vegetarianStatus:'none',allergies:[]},false,'confirmation-test',{proteinBudgetPreference:'balanced'});
const meal=plan.meals[0],date='2026-10-22',identity='user-a:'+date;
const pending={meal:structuredClone(meal),date,identity};
assert(isCurrentMealConfirmation(pending,structuredClone(meal),date,identity));
assert(!isCurrentMealConfirmation(pending,undefined,date,identity));
assert(!isCurrentMealConfirmation(pending,{...meal,consumed:true},date,identity));
assert(!isCurrentMealConfirmation(pending,meal,'2026-10-23',identity));
assert(!isCurrentMealConfirmation(pending,meal,date,'user-b:'+date));
assert(!isCurrentMealConfirmation(pending,plan.meals[1],date,identity));
const changed=structuredClone(meal);changed.components[0].grams+=25;
assert(!isCurrentMealConfirmation(pending,changed,date,identity),'An edited portion must be reviewed again');
assert(!isCurrentMealConfirmation(pending,{...meal,totalKcal:meal.totalKcal+50},date,identity));
console.log('✓ Meal confirmation accepts only the reviewed, unconsumed menu for the same date and user; rejects stale portions, calories, slot and duplicate records');
